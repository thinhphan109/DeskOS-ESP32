"""Generate sparse LovyanGFX fonts from OFL Noto Sans; no runtime font files.

Usage: python firmware/tools/make_music_fonts.py FONT_DIRECTORY
Sources: https://github.com/notofonts/noto-fonts/tree/main/hinted/ttf/NotoSans
Copy the upstream LICENSE alongside the generated header before distributing.
"""
from pathlib import Path
import hashlib
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CODES = sorted(set(range(32, 127)) | set(range(192, 256)) |
               {0xb7, 0x102, 0x103, 0x110, 0x111, 0x128, 0x129, 0x168, 0x169,
                0x1a0, 0x1a1, 0x1af, 0x1b0, 0x2013, 0x2014, 0x2018, 0x2019,
                0x201c, 0x201d, 0x2026} | set(range(0x1ea0, 0x1efa)))


def generate(directory: Path) -> None:
    lines = ['// Generated by firmware/tools/make_music_fonts.py. Noto Sans / SIL OFL 1.1.',
             '#pragma once', '#include <LovyanGFX.hpp>', 'namespace MusicFonts {']
    for name, file, size in [('body', 'NotoSans-Regular.ttf', 14),
                             ('title', 'NotoSans-Bold.ttf', 20)]:
        path = directory / file
        font = ImageFont.truetype(str(path), size)
        lines.append(f'// {file} SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}')
        bitmap, glyphs, ranges = [], [], []
        for index, code in enumerate(CODES):
            ch = chr(code)
            left, top, right, bottom = font.getbbox(ch, anchor='ls')
            width, height = right-left, bottom-top
            image = Image.new('L', (max(1, width), max(1, height)))
            ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255, anchor='ls')
            bits = [int(image.getpixel((x, y)) >= 112) for y in range(height) for x in range(width)]
            offset = len(bitmap)
            for p in range(0, len(bits), 8):
                bitmap.append(sum(bit << (7-i) for i, bit in enumerate(bits[p:p+8])))
            glyphs.append(f'{{{offset},{width},{height},{round(font.getlength(ch))},{left},{top}}}')
            if not ranges or code != ranges[-1][1]+1:
                ranges.append([code, code, index])
            else:
                ranges[-1][1] = code
        lines.append(f'static const uint8_t {name}Bitmap[] PROGMEM = {{')
        lines.extend(','.join(f'0x{v:02x}' for v in bitmap[i:i+24])+',' for i in range(0, len(bitmap), 24))
        lines.append('};')
        lines.append(f'static const lgfx::GFXglyph {name}Glyphs[] PROGMEM = {{'+',\n'.join(glyphs)+'};')
        lines.append(f'static const lgfx::EncodeRange {name}Ranges[] PROGMEM = {{'+
                     ','.join('{'+','.join(map(str, r))+'}' for r in ranges)+'};')
        lines.append(f'static const lgfx::GFXfont {name}((uint8_t*){name}Bitmap, '
                     f'(lgfx::GFXglyph*){name}Glyphs, {CODES[0]}, {CODES[-1]}, {size+7}, '
                     f'{len(ranges)}, (lgfx::EncodeRange*){name}Ranges);')
    lines.append('} // namespace MusicFonts')
    (ROOT/'src/render/music_fonts.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')


if __name__ == '__main__':
    generate(Path(sys.argv[1]))
