#!/usr/bin/env python3
"""Build MèoDesk Cat Pack v1 (16 poses) or v2 (16 poses x 3 frames).

Each PNG must be RGBA 144x144. The binary holds packed RGB565 little-endian
pixels in POSE-MAJOR order: all 3 frames of boot, then clock, and so on.
v1 is 663,552 bytes; v2 is 1,990,656 bytes. Both are headerless; Flash
bank metadata is generated by the ESP32 after validating SHA-256.

Example:
    python tools/make_catpack.py --images images --out my_cats.meocat
    python tools/make_catpack.py --motion-demo --out motion_demo.meocat
    python tools/make_catpack.py --motion --images animated_pngs --out custom_motion.meocat

For --motion supply 48 PNGs: boot_0.png, boot_1.png, boot_2.png,
clock_0.png ... shutdown_2.png. The demo derives a tiny 0/1/2px bounce
from the original 16 PNGs, to test the v2 transport before drawing new art.

The manifest contains only checksum/size (NO signature or network keys).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path

from PIL import Image
from pack_assets import BG, NAMES, rgb565

WIDTH = HEIGHT = 144
PACK_BYTES = len(NAMES) * WIDTH * HEIGHT * 2
MOTION_BYTES = PACK_BYTES * 3


def build(images: Path, output: Path, *, motion: bool = False,
          motion_demo: bool = False) -> dict:
    if motion and motion_demo:
        raise ValueError("Select only one: --motion or --motion-demo")
    animated = motion or motion_demo
    frame_count = 3 if animated else 1
    order = [f"{name}_{frame}" for name in NAMES for frame in range(3)] if animated else list(NAMES)
    digest = hashlib.sha256()
    if output.suffix.lower() != ".meocat":
        raise ValueError("Cat packs must end with .meocat")
    output.parent.mkdir(parents=True, exist_ok=True)
    # Validate the entire input set before truncating an existing output.
    for name in order if motion else NAMES:
        path = images / f"{name}.png"
        with Image.open(path) as original:
            if original.size != (WIDTH, HEIGHT):
                raise ValueError(f"{path}: expected 144x144, got {original.size}")
    with output.open("wb") as binary:
        for name in order:
            path = images / f"{name.rsplit('_', 1)[0] if motion_demo else name}.png"
            with Image.open(path) as original:
                img = original.convert("RGBA")
            if motion_demo:
                frame = int(name.rsplit("_", 1)[1])
                img = img.transform(
                    (WIDTH, HEIGHT), Image.Transform.AFFINE,
                    (1, 0, 0, 0, 1, frame),
                    resample=Image.Resampling.NEAREST,
                    fillcolor=(0, 0, 0, 0),
                )
            canvas = Image.new("RGBA", img.size, BG)
            canvas.alpha_composite(img)
            for y in range(HEIGHT):
                line = [rgb565(*canvas.getpixel((x, y))[:3]) for x in range(WIDTH)]
                row = struct.pack("<" + "H" * WIDTH, *line)
                binary.write(row)
                digest.update(row)
    expected = PACK_BYTES * frame_count
    if output.stat().st_size != expected:
        raise ValueError("Unexpected cat pack length")
    result = {"schema": 2 if animated else 1,
              "format": f"meodesk-catpack-rgb565le-v{2 if animated else 1}",
              "filename": output.name, "size": expected,
              "frames": order, "pose_names": list(NAMES),
              "frames_per_pose": frame_count, "motion_demo": motion_demo,
              "width": WIDTH, "height": HEIGHT,
              "sha256": digest.hexdigest(), "signature": None}
    output.with_suffix(".manifest.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--images", type=Path,
                        default=Path(__file__).resolve().parents[1] / "images")
    parser.add_argument("--out", type=Path, default=Path("meodesk_cats.meocat"))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--motion", action="store_true",
                      help="Use 48 hand-drawn *_0.png, *_1.png, *_2.png frames")
    mode.add_argument("--motion-demo", action="store_true",
                      help="Generate a gentle 3-frame bounce from the 16 source PNGs")
    args = parser.parse_args()
    print(json.dumps(build(args.images, args.out, motion=args.motion,
                           motion_demo=args.motion_demo), ensure_ascii=False, indent=2))
